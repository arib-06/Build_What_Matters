// React can replace a text node during a language switch before the new
// observer pass sees it. Keep a reverse index so a previously translated
// phrase can still be traced back to its English source on the next pass.
const CATALOG_SOURCE_BY_TRANSLATION = new Map<string, string>()
Object.entries(CATALOG).forEach(([source, phrase]) => {
  Object.entries(phrase).forEach(([locale, translation]) => {
    const normalized = translation.trim().replace(/\s+/g, ' ')
    CATALOG_SOURCE_BY_TRANSLATION.set(`${locale}:${normalized}`, source)
    CATALOG_SOURCE_BY_TRANSLATION.set(normalized, source)
  })
})

