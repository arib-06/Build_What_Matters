export function localeForLanguage(language: string): Locale {
  return LANGUAGE_LOCALES[language] ?? 'en'
}

export function translateText(value: string, language: string): string {
  const locale = localeForLanguage(language)
  if (!value.trim()) return value
  const normalized = value.trim().replace(/\s+/g, ' ')
  if (locale === 'en') {
    // React keeps the hero's text split around a styled span. Restore the
    // source separator when a prior non-English pass removed it.
    if (normalized === '1 Adults') return `${value.match(/^\s*/)?.[0] ?? ''}1 Adult${value.match(/\s*$/)?.[0] ?? ''}`
    return normalized === 'Find your way across' && !value.endsWith(' ') ? `${value} ` : value
  }
  const exact = CATALOG[normalized]?.[locale]
  if (exact) {
    // The hero heading is intentionally split for brand styling. Its first
    // fragment is followed by a translated punctuation-only span, so avoid
    // carrying the source's separator space into the translated sentence.
    if (normalized === 'Find your way across') return `${value.match(/^\s*/)?.[0] ?? ''}${exact}`
    return preserveWhitespace(value, exact)
  }
  const dynamic = translateDynamic(normalized, locale)
  return dynamic ? preserveWhitespace(value, dynamic) : value
}

type TextRecord = { source: string; translated: string }
const textRecords = new WeakMap<Text, TextRecord>()
const attributeRecords = new WeakMap<Element, Map<string, TextRecord>>()
const optionRecords = new WeakMap<HTMLOptionElement, TextRecord>()

const isExcluded = (element: Element | null) => Boolean(element?.closest('script, style, input, textarea, .topbar-actions'))

function localizeRoot(root: HTMLElement, language: string) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  let node = walker.nextNode()
  while (node) {
    const textNode = node as Text
    if (!isExcluded(textNode.parentElement)) {
      const current = textNode.nodeValue ?? ''
      const previous = textRecords.get(textNode)
      const source = previous && current === previous.translated ? previous.source : recoverSource(current, language)
      const translated = translateText(source, language)
      textRecords.set(textNode, { source, translated })
      if (current !== translated) textNode.nodeValue = translated
    }
    node = walker.nextNode()
  }

  // Native option labels are split into several text nodes by Chromium
  // (for example, `2 Adults` becomes `2`, a space, and `Adults`). Translate
  // the option as a whole so traveller counts and sort choices are readable.
  root.querySelectorAll<HTMLOptionElement>('option').forEach((option) => {
    const current = option.textContent ?? ''
    const previous = optionRecords.get(option)
    const source = previous && current === previous.translated ? previous.source : recoverSource(current, language)
    const translated = translateText(source, language)
    optionRecords.set(option, { source, translated })
    if (current !== translated) option.textContent = translated
  })

  root.querySelectorAll<HTMLElement>('[aria-label], [placeholder], [title]').forEach((element) => {
    // Search inputs keep their English aria-labels because SearchForm uses
    // those stable selectors to read the latest values. Passenger fields do
    // not rely on selector lookups, so their accessible labels/placeholders
    // can follow the selected language safely.
    if (isExcluded(element) && !element.matches('input[aria-label^="Passenger"]')) return
    const records = attributeRecords.get(element) ?? new Map<string, TextRecord>()
    ;['aria-label', 'placeholder', 'title'].forEach((attribute) => {
      const current = element.getAttribute(attribute)
      if (!current) return
      const previous = records.get(attribute)
      const source = previous && current === previous.translated ? previous.source : recoverSource(current, language)
      const translated = translateText(source, language)
      records.set(attribute, { source, translated })
      if (current !== translated) element.setAttribute(attribute, translated)
    })
    attributeRecords.set(element, records)
  })
}

/** Apply the local catalogue to the rendered UI without changing app state or booking logic. */
export function useLanguageLocalization(language: string) {
  useEffect(() => {
    const root = document.getElementById('root')
    if (!root) return undefined
    let observer: MutationObserver
    const apply = () => {
      observer?.disconnect()
      localizeRoot(root, language)
      observer?.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ['aria-label', 'placeholder', 'title'] })
    }
    observer = new MutationObserver(apply)
    apply()
    return () => observer.disconnect()
  }, [language])
}
